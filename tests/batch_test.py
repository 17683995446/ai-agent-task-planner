def run_batch_test():
    """运行大批量测试"""
    print("=" * 70)
    print("大批量常规文本任务规划适配测试")
    print("=" * 70)
    
    orchestrator = OrchestratorInterface()
    
    results = {
        "total": len(TEST_CASES),
        "success": 0,
        "failed": 0,
        "simple_success": 0,
        "medium_success": 0,
        "complex_success": 0,
        "total_time": 0,
        "avg_time": 0,
        "errors": []
    }
    
    print(f"\n总测试用例数: {len(TEST_CASES)}")
    print("开始测试...\n")
    
    for i, requirement in enumerate(TEST_CASES, 1):
        start_time = time.time()
        
        try:
            result = orchestrator.plan_task(requirement)
            elapsed = time.time() - start_time
            
            if result.success:
                results["success"] += 1
                if i <= 30:
                    results["simple_success"] += 1
                elif i <= 60:
                    results["medium_success"] += 1
                else:
                    results["complex_success"] += 1
            else:
                results["failed"] += 1
                results["errors"].append({
                    "index": i,
                    "requirement": requirement[:50],
                    "error": result.error_message
                })
            
            results["total_time"] += elapsed
            
            # 每10条输出一次进度
            if i % 10 == 0:
                print(f"  进度: {i}/{len(TEST_CASES)} ({i/len(TEST_CASES)*100:.0f}%)")
                
        except Exception as e:
            results["failed"] += 1
            results["errors"].append({
                "index": i,
                "requirement": requirement[:50],
                "error": str(e)
            })
    
    # 计算统计
    results["avg_time"] = results["total_time"] / len(TEST_CASES)
    success_rate = results["success"] / len(TEST_CASES) * 100
    
    # 输出结果
    print("\n" + "=" * 70)
    print("测试结果汇总")
    print("=" * 70)
    print(f"总用例数: {results['total']}")
    print(f"成功数: {results['success']}")
    print(f"失败数: {results['failed']}")
    print(f"成功率: {success_rate:.1f}%")
    print(f"总耗时: {results['total_time']:.3f}s")
    print(f"平均耗时: {results['avg_time']:.3f}s")
    print(f"\n简单任务(1-30): {results['simple_success']}/30")
    print(f"中等任务(31-60): {results['medium_success']}/30")
    print(f"复杂任务(61-100): {results['complex_success']}/40")
    
    if results["errors"]:
        print(f"\n失败用例 (前10条):")
        for error in results["errors"][:10]:
            print(f"  [{error['index']}] {error['requirement']}...")
            print(f"      错误: {error['error'][:100]}")
    
    if success_rate >= 90:
        print("\n✅ 大批量测试通过！成功率超过90%")
    else:
        print(f"\n⚠️ 测试完成，成功率 {success_rate:.1f}%")
    
    print("=" * 70)
    
    return results


if __name__ == "__main__":
    run_batch_test()
